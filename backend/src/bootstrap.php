<?php
declare(strict_types=1);

/**
 * Bootstraps the app: PSR-4 style autoloader for the "App\" namespace and .env loading.
 * (We don't use Composer, so this ~15-line autoloader replaces vendor/autoload.php.)
 */
spl_autoload_register(function (string $class): void {
    $prefix = 'App\\';
    if (!str_starts_with($class, $prefix)) {
        return;
    }
    $file = __DIR__ . '/' . str_replace('\\', '/', substr($class, strlen($prefix))) . '.php';
    if (is_file($file)) {
        require $file;
    }
});

// Load backend/.env (KEY=VALUE lines) without overriding real environment variables.
$envFile = dirname(__DIR__) . '/.env';
if (is_file($envFile)) {
    foreach (file($envFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
        $line = trim($line);
        if ($line === '' || str_starts_with($line, '#') || !str_contains($line, '=')) {
            continue;
        }
        [$key, $value] = array_map('trim', explode('=', $line, 2));
        if (getenv($key) === false) {
            putenv("$key=" . trim($value, "\"'"));
        }
    }
}
